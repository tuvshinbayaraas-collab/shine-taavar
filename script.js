// Тоглоомыг шинээр эхлүүлэх
function ehluuleh() {
    onoo = 0;
    odoogiinIndex = 0;
    hariulsanEseh = false;
    document.getElementById("current-score").innerText = onoo;
    document.getElementById("game-box").style.display = "block";
    document.getElementById("result-box").style.display = "none";

    // Тухайн сэдвийн 50 асуултыг бүгдийг нь хольж санамсаргүй болгоод эхний 10-ыг нь тасалж авна
    const holisonSan = shuffleArray(asuultuudiinSan[songosonAngilal]);
    odoogiinAsuultuud = holisonSan.slice(0, 10);

    asuultHaruulah();
}

// Нэг асуултыг дэлгэцэнд зурах
function asuultHaruulah() {
    hariulsanEseh = false;
    const a = odoogiinAsuultuud[odoogiinIndex];

    document.getElementById("question-progress").innerText = `Асуулт: ${odoogiinIndex + 1} / 10`;
    document.getElementById("question-text").innerText = a.q;

    // Сонголтуудыг ч бас байрыг нь санамсаргүй хольж байрлуулна
    const optionsContainer = document.getElementById("options-container");
    optionsContainer.innerHTML = "";

    // Анхны зөв хариултын текст
    const correctText = a.a[a.c];
    const shuffledOptions = shuffleArray(a.a);

    shuffledOptions.forEach(optText => {
        const btn = document.createElement("button");
        btn.className = "opt-btn";
        btn.innerText = optText;

        btn.onclick = () => hariultShalgah(optText, correctText, btn);
        optionsContainer.appendChild(btn);
    });
}

// Хариулт шалгах
function hariultShalgah(songoson, zov, btnElement) {
    if (hariulsanEseh) return; // Нэг асуултад олон дахин дарж болохгүй
    hariulsanEseh = true;

    const buhTovchuud = document.querySelectorAll(".opt-btn");
    buhTovchuud.forEach(b => b.disabled = true);

    if (songoson === zov) {
        // ЗӨВ
        btnElement.classList.add("correct");
        onoo += 10;
        document.getElementById("current-score").innerText = onoo;
        zuvHooloiYarih(); // "Зөв байна" гэж хэлнэ
    } else {
        // БУРУУ
        btnElement.classList.add("wrong");
        // Зөв хариултыг ногооноор тодруулж харуулна
        buhTovchuud.forEach(b => {
            if (b.innerText === zov) b.classList.add("correct");
        });
        buruuChimeeDuugarah(); // Түгшүүртэй чимээ
    }

    // 1.5 секундийн дараа дараагийн асуулт руу шилжих
    setTimeout(() => {
        odoogiinIndex++;
        if (odoogiinIndex < 10) {
            asuultHaruulah();
        } else {
            // Тоглоом дуусах
            duusgavarHaruulah();
        }
    }, 1500);
}

// Тоглоом дуусах үе
function duusgavarHaruulah() {
    document.getElementById("game-box").style.display = "none";
    document.getElementById("result-box").style.display = "block";
    document.getElementById("final-score").innerText = `${onoo} оноо`;
}

