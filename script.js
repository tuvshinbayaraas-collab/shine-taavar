// 1. Эмэгтэй хоолойгоор "Зөв байна" гэж хэлэх (Web Speech Synthesis)
function zuvHooloiYarih() {
    if ('speechSynthesis' in window) {
        window.speechSynthesis.cancel(); // Өмнөх яриаг зогсоох
        const utterance = new SpeechSynthesisUtterance("Зөв байна");
        utterance.lang = "mn-MN"; // Монгол хэлний дуудлага
        utterance.rate = 1.0;
        utterance.pitch = 1.3; // Арай өндөр буюу эмэгтэйлэг өнгө

        // Боломжтой бол эмэгтэй хоолойг хайж оноох
        const voices = window.speechSynthesis.getVoices();
        const femaleVoice = voices.find(v => v.name.toLowerCase().includes("female") || v.name.toLowerCase().includes("woman"));
        if (femaleVoice) {
            utterance.voice = femaleVoice;
        }

        window.speechSynthesis.speak(utterance);
    }
}

// 2. Буруу хариулбал: Түгшүүртэй богино "буззер" дуу үүсгэх (Web Audio API)
function buruuChimeeDuugarah() {
    try {
        const audioCtx = new (window.AudioContext || window.webkitAudioContext)();
        const osc = audioCtx.createOscillator();
        const gain = audioCtx.createGain();

        // Түгшүүртэй хүнд хөрөө шиг долгион (sawtooth)
        osc.type = "sawtooth";
        osc.frequency.setValueAtTime(130, audioCtx.currentTime); // Бага давтамжтай эхэлнэ
        osc.frequency.linearRampToValueAtTime(80, audioCtx.currentTime + 0.35); // Доошилж унана

        gain.gain.setValueAtTime(0.25, audioCtx.currentTime);
        gain.gain.exponentialRampToValueAtTime(0.01, audioCtx.currentTime + 0.35);

        osc.connect(gain);
        gain.connect(audioCtx.destination);

        osc.start();
        osc.stop(audioCtx.currentTime + 0.35);
    } catch (e) {
        console.log("Audio алдаа:", e);
    }
}

